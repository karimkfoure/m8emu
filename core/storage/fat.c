static int grow(m8_fat_card *c,size_t max_size)
{
    size_t limit=max_size<128*MIB?max_size:128*MIB;
    size_t roots=entries_count(c->root)+2;
    if(roots<512)roots=512;
    roots=(roots+15)/16*16;
    for(size_t size=(c->size/MIB+1)*MIB;size<=limit;size+=MIB){
        uint32_t spc,fat,count;
        if(roots>65520 || !format_geometry(size,(uint32_t)roots,&spc,&fat,&count))continue;
        if(required_clusters(c->root,(size_t)spc*512,1)>count)continue;
        unsigned char *image=blank_image(size,(uint32_t)roots);
        if(!image)return fail(c,M8_FAT_MEMORY,"","Cannot allocate a larger SD card");
        free(c->image);c->image=image;c->size=size;reset_chains(c->root);
        memset(&c->error,0,sizeof c->error);
        if(geometry(c))return c->error.code;
        /* The volume label and boot label must agree after a format change. */
        memcpy(c->image+c->base+43,c->label[0]?c->label:(const unsigned char *)"NO NAME    ",11);
        return flush(c);
    }
    return fail(c,M8_FAT_NO_SPACE,"","Files do not fit in the SD card (128 MiB maximum)");
}
