static int edit(m8_fat_card *c,const char *path,const void *bytes,size_t size,m8_fat_time modified,int operation)
{
    node *parent=c->root;const char *p=path;unsigned depth=0;
    while(*p){
        const char *slash=strchr(p,'/');size_t length=slash?(size_t)(slash-p):strlen(p);
        char name[1024];memcpy(name,p,length);name[length]=0;depth++;
        node *old=child_node(parent,name);
        if(slash || operation==1){
            if(old && !old->directory)return fail(c,M8_FAT_CONFLICT,path,"A path component is a file");
            if(!old && operation==2)return fail(c,M8_FAT_NOT_FOUND,path,"The file or folder does not exist");
            if(!old){
                old=m8_fat_new_node(name,1);if(!old)return fail(c,M8_FAT_MEMORY,path,"Cannot allocate FAT folder");
                if(set_path(c,old,parent->path) || m8_fat_add_child(parent,old)){m8_fat_free_node(old);return fail(c,M8_FAT_MEMORY,path,"Cannot allocate FAT folder path");}
                set_time(old,modified);old->dirty=1;
            }
            if(!slash)return 0;
            parent=old;p=slash+1;continue;
        }
        if(operation==2){
            if(!old)return fail(c,M8_FAT_NOT_FOUND,path,"The file or folder does not exist");
        }else if(old && old->directory)return fail(c,M8_FAT_CONFLICT,path,"The path is a folder");
        node *replacement=NULL;
        if(operation==0){
            replacement=m8_fat_new_node(name,0);if(!replacement)return fail(c,M8_FAT_MEMORY,path,"Cannot allocate FAT file");
            if(set_path(c,replacement,parent->path)){m8_fat_free_node(replacement);return c->error.code;}
            replacement->size=size;replacement->data=size?malloc(size):NULL;replacement->dirty=1;
            if(size && !replacement->data){m8_fat_free_node(replacement);return fail(c,M8_FAT_MEMORY,path,"Cannot copy FAT file data");}
            if(size)memcpy(replacement->data,bytes,size);
            set_time(replacement,modified);
        }
        if(old){
            for(size_t i=0;i<parent->child_count;i++)if(parent->children[i]==old){
                memmove(parent->children+i,parent->children+i+1,(parent->child_count-i-1)*sizeof *parent->children);parent->child_count--;break;
            }
            release_chain(c,old);m8_fat_free_node(old);
        }
        if(replacement && m8_fat_add_child(parent,replacement)){m8_fat_free_node(replacement);return fail(c,M8_FAT_MEMORY,path,"Cannot add FAT file");}
        return 0;
    }
    (void)depth;return 0;
}
static m8_fat_result mutate(m8_fat_card *c,const char *path,const void *bytes,size_t size,m8_fat_time modified,size_t max_size,int operation)
{
    if(valid_path(c,path,0))return c->error.code;
    if(operation==0 && ((!bytes && size) || size>UINT32_MAX))return fail(c,M8_FAT_INVALID,path,"Invalid FAT file buffer");
    if(operation==0 && size>128*MIB && max_size)return fail(c,M8_FAT_NO_SPACE,path,"Files do not fit in the SD card (128 MiB maximum)");
    m8_fat_card *candidate=NULL;
    m8_fat_result result=m8_fat_open(c->image,c->size,&candidate,&c->error);
    if(result)return result;
    result=(m8_fat_result)edit(candidate,path,bytes,size,modified,operation);
    if(!result){
        sort_tree(candidate->root);result=(m8_fat_result)flush(candidate);
        if(result==M8_FAT_NO_SPACE && max_size>c->size)result=(m8_fat_result)grow(candidate,max_size);
        else if(result==M8_FAT_NO_SPACE && max_size)
            result=fail(candidate,M8_FAT_NO_SPACE,path,"Files do not fit in the SD card (128 MiB maximum)");
    }
    if(result){
        c->error=candidate->error;
        if(!c->error.path[0])snprintf(c->error.path,sizeof c->error.path,"%s",path);
    }else{
        candidate->changed=1;
        m8_fat_card temporary=*c;*c=*candidate;*candidate=temporary;
    }
    m8_fat_close(candidate);return result;
}
