static int format_geometry(size_t size,uint32_t roots,uint32_t *spc_out,uint32_t *fat_out,uint32_t *count_out)
{
    if(size<3*MIB || size>128*MIB || size%MIB || roots>65520)return 0;
    uint32_t partition=(uint32_t)(size/512)-64,root_sectors=(roots*32+511)/512;
    for(uint32_t spc=1;spc<=128;spc*=2){
        uint32_t fat=1,count;
        for(;;){
            if(8+2*fat+root_sectors>=partition)return 0;
            count=(partition-8-2*fat-root_sectors)/spc;
            uint32_t need=((count+2)*2+511)/512;
            if(need<=fat)break;
            fat=need;
        }
        if(count>=4085 && count<65525){*spc_out=spc;*fat_out=fat;*count_out=count;return 1;}
    }
    return 0;
}
