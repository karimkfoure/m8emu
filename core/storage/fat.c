        int valid=base && base<=8 && ext<=3 && (!dot || !strchr(dot+1,'.'));
        for(size_t j=0;valid && j<base+ext;j++){
            unsigned c=(unsigned char)(j<base?n->name[j]:dot[1+j-base]);if(c>='a' && c<='z')c-=32;
            if(!short_allowed(c))valid=0;else candidate[j<base?j:8+j-base]=(unsigned char)c;
        }
