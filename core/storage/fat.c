static int utf8_next(const char **text, uint32_t *code)
{
    const unsigned char *p=(const unsigned char *)*text;
    uint32_t value; unsigned count; uint32_t minimum;
    if (!*p) return 0;
    if (*p<0x80) { *code=*p; (*text)++; return 1; }
    if ((*p&0xe0)==0xc0) { value=*p&31;count=1;minimum=0x80; }
    else if ((*p&0xf0)==0xe0) { value=*p&15;count=2;minimum=0x800; }
    else if ((*p&0xf8)==0xf0) { value=*p&7;count=3;minimum=0x10000; }
    else return -1;
    for (unsigned i=1;i<=count;i++) {
        if (!p[i] || (p[i]&0xc0)!=0x80) return -1;
        value=(value<<6)|(p[i]&63);
    }
    if (value<minimum || value>0x10ffff || (value>=0xd800 && value<=0xdfff)) return -1;
    *code=value; *text+=(count+1); return 1;
}
static char *utf8_put(char *p, uint32_t code)
{
    if (code<0x80) *p++=(char)code;
    else if (code<0x800) { *p++=(char)(0xc0|(code>>6)); *p++=(char)(0x80|(code&63)); }
    else if (code<0x10000) { *p++=(char)(0xe0|(code>>12)); *p++=(char)(0x80|((code>>6)&63)); *p++=(char)(0x80|(code&63)); }
    else { *p++=(char)(0xf0|(code>>18)); *p++=(char)(0x80|((code>>12)&63)); *p++=(char)(0x80|((code>>6)&63)); *p++=(char)(0x80|(code&63)); }
    return p;
}
static size_t utf16_name(const char *name, uint16_t units[NAME_UNITS])
{
    const char *p=name; uint32_t code; size_t count=0; int rc;
    if (!*name || !strcmp(name,".") || !strcmp(name,"..")) return 0;
    size_t bytes=strlen(name);
    if (name[bytes-1]=='.' || name[bytes-1]==' ') return 0;
    while ((rc=utf8_next(&p,&code))>0) {
        if (code<32 || code==127 || (code<128 && strchr("\\/:*?\"<>|",(int)code))) return 0;
        if (count+(code>0xffff ? 2:1)>NAME_UNITS) return 0;
        if (code>0xffff) { code-=0x10000; units[count++]=(uint16_t)(0xd800|(code>>10)); units[count++]=(uint16_t)(0xdc00|(code&1023)); }
        else units[count++]=(uint16_t)code;
    }
    return rc<0 ? 0:count;
}
static char *fold_name(const char *name)
{
    size_t n=strlen(name);
    if (n>(SIZE_MAX-1)/3) return NULL;
    char *folded=malloc(n*3+1), *out=folded;
    if (!folded) return NULL;
    const char *p=name; uint32_t code; int rc;
    while ((rc=utf8_next(&p,&code))>0) {
        size_t lo=0,hi=sizeof fold_table/sizeof *fold_table;
        while (lo<hi) { size_t mid=lo+(hi-lo)/2; if(fold_table[mid].code<code) lo=mid+1;else hi=mid; }
        if (lo<sizeof fold_table/sizeof *fold_table && fold_table[lo].code==code) {
            for(unsigned i=0;i<3 && fold_table[lo].folded[i];i++) out=utf8_put(out,fold_table[lo].folded[i]);
        } else out=utf8_put(out,code);
    }
    if (rc<0) { free(folded); return NULL; }
    *out=0; return folded;
}

