static int utf8_next(const char **text, uint32_t *code)
{
    const unsigned char *p=(const unsigned char *)*text;
    uint32_t value; unsigned count; uint32_t minimum;
    if (!*p) return 0;
    if (*p<0x80) { *code=*p; (*text)++; return 1; }
    if ((*p&0xe0)==0xc0) { value=*p&31;count=1;minimum=0x80; }
    else if ((*p&0xf0)==0xe0) { value=*p&15;count=2;minimum=0x800; }
    else if ((*p&0xf8)==0xf0) { value=*p&7;count=3;minimum=0x10000; }
    else return -1;
    for (unsigned i=1;i<=count;i++) {
        if (!p[i] || (p[i]&0xc0)!=0x80) return -1;
        value=(value<<6)|(p[i]&63);
    }
    if (value<minimum || value>0x10ffff || (value>=0xd800 && value<=0xdfff)) return -1;
    *code=value; *text+=(count+1); return 1;
}
